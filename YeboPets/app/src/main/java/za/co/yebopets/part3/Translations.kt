@Composable fun T(english:String):String {
    workspaceLabels[english]?.let { return stringResource(it) }
    journeyLabels[english]?.let { return stringResource(it) }
    labels[english]?.let { return stringResource(it) }
    for((pattern,id) in formats) {
        val match=pattern.matchEntire(english) ?: continue
        return stringResource(id,*match.groupValues.drop(1).toTypedArray())
    }
    return english
}
